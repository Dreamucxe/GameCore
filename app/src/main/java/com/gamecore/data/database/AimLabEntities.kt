/**
 * A control layout's own row; its controls are separate rows in [AimLabControlEntity].
 *
 * Same split — and same reasoning — as `hud_layouts`/`hud_widgets`: rows, not a JSON blob, so the data
 * goes through Room's type checking and an imported layout cannot smuggle a hand-parsed structure past it.
 */
@Entity(tableName = "aimlab_layouts")
data class AimLabLayoutEntity(
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "id")
    val id: Long,

    @ColumnInfo(name = "name")
    val name: String,

    @ColumnInfo(name = "created_at")
    val createdAtMillis: Long,

    @ColumnInfo(name = "updated_at")
    val updatedAtMillis: Long,
)

/**
 * One control on one layout.
 *
 * The primary key is `(layout_id, role)`: a role is unique within a layout — there is one Shoot button —
 * so the pair identifies a control without a surrogate id. No FK cascade, for the reason the class note on
 * [HudWidgetEntity] gives; children are deleted explicitly in the DAO's save/delete transactions.
 */
@Entity(
    tableName = "aimlab_controls",
    primaryKeys = ["layout_id", "role", "orientation"],
    indices = [Index("layout_id")],
)
data class AimLabControlEntity(
    @ColumnInfo(name = "layout_id")
    val layoutId: Long,

    @ColumnInfo(name = "role")
    val role: String,

    @ColumnInfo(name = "x_fraction")
    val xFraction: Float,

    @ColumnInfo(name = "y_fraction")
    val yFraction: Float,

    @ColumnInfo(name = "width_fraction")
    val widthFraction: Float,

    @ColumnInfo(name = "height_fraction")
    val heightFraction: Float,

    @ColumnInfo(name = "opacity_percent")
    val opacityPercent: Int,

    @ColumnInfo(name = "shape")
    val shape: String,

    @ColumnInfo(name = "enabled")
    val enabled: Boolean,

    /**
     * Which orientation this placement belongs to, added in schema version 9 for landscape support.
     *
     * A layout now stores two arrangements of the same controls: one for portrait, one for landscape,
     * each a set of fractions of that orientation's safe area. The value is a [ControlOrientation] name
     * (`PORTRAIT`/`LANDSCAPE`). `NOT NULL DEFAULT 'PORTRAIT'` in the migration, so every control that
     * existed before version 9 becomes the layout's portrait set — which is what it always was. The
     * primary key gains this column so the two orientations coexist for one role in one layout.
     */
    @ColumnInfo(name = "orientation", defaultValue = "PORTRAIT")
    val orientation: String = "PORTRAIT",
)

/**
 * A layout and all its controls in one query, the single source the list, the editor and the training
 * screen all read through (§bug-fix): the "N of M controls enabled" count and the drawn overlay are then
 * the same real rows, never an editor-only in-memory preset on one side and empty rows on the other.
 */
data class AimLabLayoutWithControls(
    @Embedded val layout: AimLabLayoutEntity,
    @Relation(parentColumn = "id", entityColumn = "layout_id")
    val controls: List<AimLabControlEntity>,
)

/**
 * A personal record row, one per (mode, difficulty, weapon, metric).
 *
 * A stored table rather than a query-time derivation because a record carries the value it *beat*
 * ([previousValue]) and the moment it was set, neither of which survives recomputation from sessions. The
 * unique index on the four key columns is what makes "is this a new record for this combination" a single
 * upsert. `weapon_name` is nullable and part of the key, so weapon-less modes share one slot.
 */
@Entity(
    tableName = "aimlab_records",
    indices = [
        Index(
            value = ["mode", "difficulty", "weapon_name", "metric", "scoring_version"],
            unique = true,
        ),
    ],
)
data class AimLabRecordEntity(
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "id")
    val id: Long,

    @ColumnInfo(name = "mode")
    val mode: String,

    @ColumnInfo(name = "difficulty")
    val difficulty: String,

    @ColumnInfo(name = "weapon_name")
    val weaponName: String?,

    @ColumnInfo(name = "metric")
    val metric: String,

    @ColumnInfo(name = "value")
    val value: Float,

    @ColumnInfo(name = "previous_value")
    val previousValue: Float?,

    @ColumnInfo(name = "achieved_at")
    val achievedAtMillis: Long,

    /**
     * The scoring generation this record belongs to (§6), added in schema version 8 and part of the
     * unique key. A 3D record and a 2D record for the same mode/difficulty/weapon/metric are different
     * measurements and coexist as separate rows; the repository only ever challenges a record of the same
     * version. `NOT NULL DEFAULT 1`, so every pre-existing record is a legacy-2D record.
     */
    @ColumnInfo(name = "scoring_version", defaultValue = "1")
    val scoringVersion: Int,
)
