package com.gamecore.data.database

import androidx.room.ColumnInfo
import androidx.room.Embedded
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import androidx.room.Relation

/**
 * The Aim Lab tables, added in schema version 7.
 *
 * All of them live inside the existing encrypted `gamecore-store` database, so nothing here handles
 * keys or encryption — the SQLCipher passphrase set up in `DatabaseModule` covers these rows exactly as
 * it does the rest. Every one follows the conventions the existing tables set: snake_case `@ColumnInfo`
 * names, autogenerated `Long` ids, enums stored as their `.name` string and parsed back defensively in
 * [AimLabMappers], and — for the two-table layout — no foreign-key cascade (the DAO deletes children in a
 * transaction, because SQLCipher only honours FKs when the per-connection pragma is set).
 *
 * The session row is a summary written once when a run ends; there is no per-frame table, because the
 * high-frequency training data lives in memory during the run and never reaches Room (§18).
 */
@Entity(tableName = "aimlab_sessions", indices = [Index("mode"), Index("started_at")])
data class AimLabSessionEntity(
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "id")
    val id: Long,

    @ColumnInfo(name = "mode")
    val mode: String,

    @ColumnInfo(name = "difficulty")
    val difficulty: String,

    @ColumnInfo(name = "started_at")
    val startedAtMillis: Long,

    @ColumnInfo(name = "ended_at")
    val endedAtMillis: Long,

    @ColumnInfo(name = "weapon_name")
    val weaponName: String?,

    @ColumnInfo(name = "sensitivity_name")
    val sensitivityName: String?,

    @ColumnInfo(name = "score")
    val score: Int,

    @ColumnInfo(name = "hits")
    val hits: Int,

    @ColumnInfo(name = "shots")
    val shots: Int,

    @ColumnInfo(name = "targets_missed")
    val targetsMissed: Int,

    @ColumnInfo(name = "reaction_attempts")
    val reactionAttempts: Int,

    @ColumnInfo(name = "reaction_fastest")
    val reactionFastest: Long,

    @ColumnInfo(name = "reaction_slowest")
    val reactionSlowest: Long,

    @ColumnInfo(name = "reaction_avg")
    val reactionAverage: Float,

    @ColumnInfo(name = "reaction_median")
    val reactionMedian: Float,

    @ColumnInfo(name = "avg_acquire")
    val averageAcquireMillis: Float,

    @ColumnInfo(name = "tracking_error_avg")
    val trackingErrorAverage: Float,

    @ColumnInfo(name = "time_on_target")
    val timeOnTargetFraction: Float,

    @ColumnInfo(name = "recoil_compensation")
    val recoilCompensation: Float,

    @ColumnInfo(name = "gyro_stability")
    val gyroStability: Float,

    /**
     * The scoring/rendering generation that produced this row (§6), added in schema version 8.
     *
     * `NOT NULL DEFAULT 1` in the migration: every session that existed before the 3D view was a 2D-arena
     * session, and `SessionSummary.SCORING_VERSION_2D` is 1. New rows write the 3D value. This is what
     * lets history label the old sessions "legacy 2D" and keeps records from ranking a 2D result against
     * a 3D one.
     */
    @ColumnInfo(name = "scoring_version", defaultValue = "1")
    val scoringVersion: Int,
)

/** A training weapon's row. Flat: one column per parameter, including the four recoil fields. */
@Entity(tableName = "aimlab_weapons")
data class AimLabWeaponEntity(
    @PrimaryKey(autoGenerate = true)
    @ColumnInfo(name = "id")
    val id: Long,

    @ColumnInfo(name = "name")
    val name: String,

    @ColumnInfo(name = "category")
    val category: String,

    @ColumnInfo(name = "fire_rate_rpm")
    val fireRateRpm: Int,

    @ColumnInfo(name = "magazine_size")
    val magazineSize: Int,

    @ColumnInfo(name = "reload_millis")
    val reloadMillis: Long,

    @ColumnInfo(name = "ads_time_millis")
    val adsTimeMillis: Long,

    @ColumnInfo(name = "movement_penalty")
    val movementPenalty: Float,

    @ColumnInfo(name = "spread")
    val spread: Float,

    @ColumnInfo(name = "vertical_per_shot")
    val verticalPerShot: Float,

    @ColumnInfo(name = "horizontal_per_shot")
    val horizontalPerShot: Float,

    @ColumnInfo(name = "randomness")
    val randomness: Float,

    @ColumnInfo(name = "recovery_per_second")
    val recoveryPerSecond: Float,

    @ColumnInfo(name = "is_built_in")
    val isBuiltIn: Boolean,

    /**
     * How the weapon discharges — `SINGLE`/`BURST`/`AUTO` — added in schema version 10.
     *
     * `NOT NULL DEFAULT 'AUTO'` in the migration: every weapon that existed before fire modes fired
     * automatically, which is what the loop already did, so an old row reads back unchanged.
     */
    @ColumnInfo(name = "fire_mode", defaultValue = "AUTO")
    val fireMode: String = "AUTO",

    /** Rounds per burst when [fireMode] is BURST; `NOT NULL DEFAULT 3`, ignored for the other modes. */
    @ColumnInfo(name = "burst_count", defaultValue = "3")
    val burstCount: Int = 3,
)

