    private val indexById: Map<String, StudioTemplate> = ALL.associateBy { it.id }

    /** The template with [id], or null when there is no such starting point. */
    fun byId(id: String): StudioTemplate? = indexById[id]

    private fun template(
        id: String,
        name: String,
        description: String,
        theme: ThemeDraft,
    ): StudioTemplate = StudioTemplate(
        id = id,
        name = name,
        description = description,
        palette = listOf(
            theme.primary,
            theme.accent,
            theme.secondary,
            theme.tertiary,
            theme.background,
            theme.surface,
        ),
        theme = theme,
    )
