/**
 * A ready-made theme the editor can start from.
 *
 * [palette] is a short, displayable selection of the theme's colours — primary, accent,
 * secondary, tertiary, background and surface — rather than a second source of truth. The
 * [theme] is what the composer writes.
 */
data class StudioTemplate(
    val id: String,
    val name: String,
    val description: String,
    val palette: List<Long>,
    val theme: ThemeDraft,
)

